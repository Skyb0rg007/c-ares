static const struct dv_msg *FindMsg(const struct dv_msg *table,
                                    const char *name, unsigned short qtype)
{
  if (table != nullptr) {
    for (; table->name != nullptr; table++) {
      if (table->type == qtype && ares_strcaseeq(table->name, name)) {
        return table;
      }
    }
  }
  return nullptr;
}

static const struct dv_msg *FindCaseMsg(const struct dv_case &c,
                                        const char *name, unsigned short qtype)
{
  const struct dv_msg *m = FindMsg(c.override, name, qtype);
  return m ? m : FindMsg(c.table, name, qtype);
}

// Pass a message through ares_dns_parse() and ares_dns_write(), as
// ares_query_dnssec() does
static bool RoundTrip(std::vector<unsigned char> *msg)
{
  ares_dns_record_t *dnsrec = NULL;
  unsigned char     *out    = NULL;
  size_t             len    = 0;
  if (ares_dns_parse(msg->data(), msg->size(), 0, &dnsrec) != ARES_SUCCESS) {
    return false;
  }
  ares_status_t status = ares_dns_write(dnsrec, &out, &len);
  ares_dns_record_destroy(dnsrec);
  if (status != ARES_SUCCESS) {
    return false;
  }
  msg->assign(out, out + len);
  ares_free_string(out);
  return true;
}

struct DNSSECResult {
  ares_dnssec_status_t status;
  int                  rcode;
  size_t               count;
  std::string          reason;
};

static DNSSECResult RunCase(const struct dv_case &c, bool roundtrip)
{
  ares_dnssec_ctx_t *ctx = NULL;
  ares_dnssec_req_t *req = NULL;
  DNSSECResult       res = { ARES_DNSSEC_INDETERMINATE, -1, 0, "" };
  int                rounds;

  EXPECT_EQ(ARES_SUCCESS, ares_dnssec_ctx_create(TestCrypto(), &ctx));
  if (ctx == NULL) {
    return res;
  }
  if (c.anchors != nullptr) {
    ares_dnssec_ctx_clear_anchors(ctx);
    for (const char * const *a = c.anchors; *a; a++) {
      EXPECT_EQ(ARES_SUCCESS, ares_dnssec_ctx_add_anchor(ctx, *a)) << *a;
    }
  }
  ares_dnssec_ctx_set_time(ctx, (time_t)c.now);
  ares_dnssec_ctx_set_flags(ctx, c.flags);
  EXPECT_EQ(ARES_SUCCESS, ares_dnssec_req_create(
                            ctx, c.qname, (unsigned short)c.qtype, &req));
  if (req == NULL) {
    ares_dnssec_ctx_destroy(ctx);
    return res;
  }

  for (rounds = 0; rounds < 100; rounds++) {
    ares_bool_t    done = ARES_FALSE;
    char           name[ARES_DNSSEC_NAME_STRLEN];
    unsigned short qtype;

    EXPECT_EQ(ARES_SUCCESS, ares_dnssec_req_run(req, &done));
    if (done) {
      break;
    }
    while (ares_dnssec_ctx_next_query(ctx, name, sizeof(name), &qtype)) {
      const struct dv_msg *m = FindCaseMsg(c, name, qtype);
      if (m == nullptr) {
        EXPECT_EQ(ARES_SUCCESS, ares_dnssec_ctx_add_failure(ctx, name, qtype));
        continue;
      }
      std::vector<unsigned char> msg = Pieces(m->msg);
      if (roundtrip && !RoundTrip(&msg)) {
        EXPECT_EQ(ARES_SUCCESS, ares_dnssec_ctx_add_failure(ctx, name, qtype));
        continue;
      }
      EXPECT_EQ(ARES_SUCCESS, ares_dnssec_ctx_add_response(
                                ctx, name, qtype, msg.data(), msg.size()));
    }
  }
  EXPECT_LT(rounds, 100) << c.desc << ": does not finish";

  res.status = ares_dnssec_req_status(req);
  res.rcode  = ares_dnssec_req_rcode(req);
  res.count  = ares_dnssec_req_count(req);
  if (ares_dnssec_req_reason(req) != nullptr) {
    res.reason = ares_dnssec_req_reason(req);
  }
  if (res.status == ARES_DNSSEC_SECURE) {
    EXPECT_EQ(nullptr, ares_dnssec_req_reason(req)) << c.desc;
  } else {
    EXPECT_NE(nullptr, ares_dnssec_req_reason(req)) << c.desc;
  }
  if (res.count) {
    const unsigned char *rdata;
    size_t               rdlen;
    EXPECT_TRUE(ares_dnssec_req_rdata(req, res.count - 1, &rdata, &rdlen));
    EXPECT_FALSE(ares_dnssec_req_rdata(req, res.count, &rdata, &rdlen));
  }

  ares_dnssec_req_destroy(req);
  ares_dnssec_ctx_destroy(ctx);
  return res;
}

static void CheckCase(const struct dv_case &c, const DNSSECResult &res)
{
  EXPECT_EQ(c.status, res.status)
    << c.desc << ": " << ares_dnssec_status_str(res.status) << ", "
    << res.reason;
  if (c.rcode >= 0) {
    EXPECT_EQ(c.rcode, res.rcode) << c.desc;
  }
  if (c.count >= 0) {
    EXPECT_EQ((size_t)c.count, res.count) << c.desc;
  }
}

TEST_F(LibraryTest, DNSSECVectors)
{
  REQUIRE_CRYPTO();
  for (const struct dv_case &c : dv_cases) {
    CheckCase(c, RunCase(c, false));
  }
}

