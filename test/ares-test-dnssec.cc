static std::vector<unsigned char> Base64Decode(const std::string &in)
{
  std::vector<unsigned char> out;
  unsigned int               acc   = 0;
  int                        nbits = 0;
  for (char c : in) {
    int val;
    if (c >= 'A' && c <= 'Z') {
      val = c - 'A';
    } else if (c >= 'a' && c <= 'z') {
      val = c - 'a' + 26;
    } else if (c >= '0' && c <= '9') {
      val = c - '0' + 52;
    } else if (c == '+') {
      val = 62;
    } else if (c == '/') {
      val = 63;
    } else {
      continue; /* padding */
    }
    acc    = (acc << 6) | (unsigned int)val;
    nbits += 6;
    if (nbits >= 8) {
      nbits -= 8;
      out.push_back((unsigned char)(acc >> nbits));
    }
  }
  return out;
}

static std::vector<unsigned char> Pieces(const char * const *pieces)
{
  std::string b64;
  for (; *pieces; pieces++) {
    b64 += *pieces;
  }
  return Base64Decode(b64);
}

