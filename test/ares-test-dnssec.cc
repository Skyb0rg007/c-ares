static ares_status_t TestVerify(unsigned char alg, const unsigned char *key,
                                size_t key_len, const unsigned char *data,
                                size_t data_len, const unsigned char *sig,
                                size_t sig_len, void *user_data)
{
  const EVP_MD *md      = nullptr;
  bool          oneshot = false;
  Bytes         dersig(sig, sig + sig_len);
  ares_status_t status = ARES_EBADRESP;

  (void)user_data;
  switch (alg) {
    case 5:
    case 7:
      md = EVP_sha1();
      break;
    case 8:
    case 13:
      md = EVP_sha256();
      break;
    case 10:
      md = EVP_sha512();
      break;
    case 14:
      md = EVP_sha384();
      break;
    default:
      oneshot = true;
      break;
  }
  if (alg == 13 || alg == 14) {
    // RFC 6605 section 4: r | s, to ECDSA-Sig-Value
    Bytes seq = DerUint(sig, sig_len / 2);
    Bytes s2  = DerUint(sig + sig_len / 2, sig_len / 2);
    seq.insert(seq.end(), s2.begin(), s2.end());
    dersig = DerTag(0x30, seq);
  }

  Bytes                der   = Spki(alg, key, key_len);
  const unsigned char *p     = der.data();
  EVP_PKEY            *pkey  = d2i_PUBKEY(nullptr, &p, (long)der.size());
  EVP_MD_CTX          *mdctx = EVP_MD_CTX_new();
  if (pkey != nullptr && mdctx != nullptr &&
      EVP_DigestVerifyInit(mdctx, nullptr, md, nullptr, pkey) == 1) {
    int rc;
    if (oneshot) {
      rc =
        EVP_DigestVerify(mdctx, dersig.data(), dersig.size(), data, data_len);
    } else {
      rc = (EVP_DigestVerifyUpdate(mdctx, data, data_len) == 1)
             ? EVP_DigestVerifyFinal(mdctx, dersig.data(), dersig.size())
             : 0;
    }
    if (rc == 1) {
      status = ARES_SUCCESS;
    }
  }
  EVP_MD_CTX_free(mdctx);
  EVP_PKEY_free(pkey);
  ERR_clear_error();
  return status;
}

static const EVP_MD *DigestMd(unsigned char digest_type)
{
  switch (digest_type) {
    case 1:
      return EVP_sha1();
    case 2:
      return EVP_sha256();
    case 4:
      return EVP_sha384();
    default:
      return nullptr;
  }
}

static ares_bool_t TestDigestSupported(unsigned char digest_type,
                                       void         *user_data)
{
  (void)user_data;
  return DigestMd(digest_type) != nullptr ? ARES_TRUE : ARES_FALSE;
}

static ares_status_t TestDigest(unsigned char        digest_type,
                                const unsigned char *data, size_t data_len,
                                unsigned char *out, size_t *out_len,
                                void *user_data)
{
  const EVP_MD *md  = DigestMd(digest_type);
  unsigned int  len = 0;
  (void)user_data;
  if (md == nullptr || *out_len < (size_t)EVP_MD_size(md) ||
      EVP_Digest(data, data_len, out, &len, md, nullptr) != 1) {
    return ARES_EFORMERR;
  }
  *out_len = len;
  return ARES_SUCCESS;
}

