// Crypto functions that count the calls, for checking what c-ares does
// around them
struct FakeCrypto {
  int           verify_calls  = 0;
  ares_status_t verify_status = ARES_SUCCESS;
  int           digest_calls  = 0;
  size_t        digest_len    = 20;
  ares_status_t digest_status = ARES_SUCCESS;
};

static ares_bool_t FakeAlgSupported(unsigned char alg, void *user_data)
{
  (void)user_data;
  return (alg != 14) ? ARES_TRUE : ARES_FALSE;
}

static ares_status_t FakeVerify(unsigned char alg, const unsigned char *key,
                                size_t key_len, const unsigned char *data,
                                size_t data_len, const unsigned char *sig,
                                size_t sig_len, void *user_data)
{
  FakeCrypto *f = (FakeCrypto *)user_data;
  (void)alg;
  (void)key;
  (void)key_len;
  (void)data;
  (void)data_len;
  (void)sig;
  (void)sig_len;
  f->verify_calls++;
  return f->verify_status;
}

static ares_bool_t FakeDigestSupported(unsigned char digest_type,
                                       void         *user_data)
{
  (void)user_data;
  return (digest_type != 4) ? ARES_TRUE : ARES_FALSE;
}

static ares_status_t FakeDigest(unsigned char        digest_type,
                                const unsigned char *data, size_t data_len,
                                unsigned char *out, size_t *out_len,
                                void *user_data)
{
  FakeCrypto *f = (FakeCrypto *)user_data;
  (void)digest_type;
  (void)data;
  (void)data_len;
  f->digest_calls++;
  memset(out, 0xab, *out_len);
  *out_len = f->digest_len;
  return f->digest_status;
}

// An RSA key (RFC 3110 section 2) with an exponent of 'explen' octets and a
// modulus of 'bits' bits
static std::vector<unsigned char> RsaKey(size_t explen, size_t bits)
{
  std::vector<unsigned char> key;
  if (explen < 256) {
    key.push_back((unsigned char)explen);
  } else {
    key.push_back(0);
    key.push_back((unsigned char)(explen >> 8));
    key.push_back((unsigned char)explen);
  }
  key.insert(key.end(), explen, 0x01);
  size_t modlen = (bits + 7) / 8;
  key.push_back((unsigned char)(0xff >> ((modlen * 8) - bits)));
  key.insert(key.end(), modlen - 1, 0x55);
  return key;
}

TEST_F(LibraryTest, DNSSECCryptoChecks)
{
  FakeCrypto                 f;
  const ares_dnssec_crypto_t crypto = { FakeAlgSupported, FakeVerify,
                                        FakeDigestSupported, FakeDigest, &f };
  const unsigned char        data[] = "signed data";
  std::vector<unsigned char> sig(1024, 0x11);
  unsigned char              out[DNSSEC_DIGEST_MAX];
  unsigned char              hash[DNSSEC_NSEC3_HASHLEN];

  auto verify = [&](unsigned char alg, const std::vector<unsigned char> &key,
                    size_t siglen) {
    return ares_dnssec_verify(&crypto, alg, key.data(), key.size(), data,
                              sizeof(data), sig.data(), siglen);
  };

  // RSA: 512 to 4096 bits, 1024 bits for RSASHA512 (RFC 3110, RFC 5702),
  // an exponent of at most 8 octets, and a signature as long as the modulus
  EXPECT_EQ(ARES_SUCCESS, verify(8, RsaKey(1, 512), 64));
  EXPECT_EQ(1, f.verify_calls);
  EXPECT_EQ(ARES_SUCCESS, verify(8, RsaKey(3, 4096), 512));
  EXPECT_EQ(ARES_SUCCESS, verify(5, RsaKey(8, 1024), 128));
  EXPECT_EQ(ARES_SUCCESS, verify(10, RsaKey(3, 1024), 128));
  // the exponent length in three octets
  std::vector<unsigned char> longexp = RsaKey(3, 1024);
  longexp.erase(longexp.begin());
  longexp.insert(longexp.begin(), { 0, 0, 3 });
  EXPECT_EQ(ARES_SUCCESS, verify(8, longexp, 128));
  EXPECT_EQ(5, f.verify_calls);
  EXPECT_EQ(ARES_EFORMERR, verify(8, RsaKey(1, 511), 64));
  EXPECT_EQ(ARES_EFORMERR, verify(8, RsaKey(1, 4097), 513));
  EXPECT_EQ(ARES_EFORMERR, verify(10, RsaKey(3, 1023), 128));
  EXPECT_EQ(ARES_EFORMERR, verify(8, RsaKey(9, 1024), 128));
  EXPECT_EQ(ARES_EFORMERR, verify(8, RsaKey(1, 1024), 127));
  EXPECT_EQ(ARES_EFORMERR, verify(8, RsaKey(300, 1024), 128));
  std::vector<unsigned char> key = RsaKey(1, 1024);
  key[2]                         = 0;  // modulus with a leading zero octet
  EXPECT_EQ(ARES_EFORMERR, verify(8, key, 128));
  EXPECT_EQ(ARES_EFORMERR, verify(8, std::vector<unsigned char>(), 128));
  EXPECT_EQ(ARES_EFORMERR, verify(8, std::vector<unsigned char>(2, 0), 128));
  EXPECT_EQ(ARES_EFORMERR, verify(8, std::vector<unsigned char>(1, 5), 128));
  EXPECT_EQ(5, f.verify_calls);

  // fixed sizes for ECDSA and EdDSA (RFC 6605, RFC 8080)
  EXPECT_EQ(ARES_SUCCESS, verify(13, std::vector<unsigned char>(64, 1), 64));
  EXPECT_EQ(ARES_SUCCESS, verify(15, std::vector<unsigned char>(32, 1), 64));
  EXPECT_EQ(ARES_SUCCESS, verify(16, std::vector<unsigned char>(57, 1), 114));
  EXPECT_EQ(8, f.verify_calls);
  EXPECT_EQ(ARES_EFORMERR, verify(13, std::vector<unsigned char>(65, 1), 64));
  EXPECT_EQ(ARES_EFORMERR, verify(13, std::vector<unsigned char>(64, 1), 63));
  EXPECT_EQ(ARES_EFORMERR, verify(15, std::vector<unsigned char>(32, 1), 65));
  EXPECT_EQ(ARES_EFORMERR, verify(16, std::vector<unsigned char>(56, 1), 114));
  // not supported by the functions, and not known by c-ares
  EXPECT_EQ(ARES_ENOTIMP, verify(14, std::vector<unsigned char>(96, 1), 96));
  EXPECT_FALSE(ares_dnssec_alg_supported(&crypto, 14));
  EXPECT_EQ(ARES_ENOTIMP, verify(1, RsaKey(1, 1024), 128));
  EXPECT_FALSE(ares_dnssec_alg_supported(&crypto, 1));
  EXPECT_FALSE(ares_dnssec_alg_supported(&crypto, 12));
  EXPECT_EQ(8, f.verify_calls);

  // anything but success or out of memory means invalid
  f.verify_status = ARES_EFORMERR;
  EXPECT_EQ(ARES_EBADRESP, verify(13, std::vector<unsigned char>(64, 1), 64));
  f.verify_status = ARES_ENOMEM;
  EXPECT_EQ(ARES_ENOMEM, verify(13, std::vector<unsigned char>(64, 1), 64));

  // digests: the lengths are checked
  f.digest_len = 32;
  EXPECT_EQ(32u, ares_dnssec_digest(&crypto, 2, data, 4, data + 4, 4, out));
  EXPECT_EQ(0u, ares_dnssec_digest(&crypto, 1, data, 4, NULL, 0, out));
  f.digest_len = 20;
  EXPECT_EQ(20u, ares_dnssec_digest(&crypto, 1, data, 4, NULL, 0, out));
  f.digest_status = ARES_ENOMEM;
  EXPECT_EQ(0u, ares_dnssec_digest(&crypto, 1, data, 4, NULL, 0, out));
  f.digest_status = ARES_SUCCESS;
  EXPECT_EQ(4, f.digest_calls);
  EXPECT_EQ(0u, ares_dnssec_digest(&crypto, 4, data, 4, NULL, 0, out));
  EXPECT_EQ(0u, ares_dnssec_digest(&crypto, 3, data, 4, NULL, 0, out));
  EXPECT_FALSE(ares_dnssec_digest_supported(&crypto, 4));
  EXPECT_FALSE(ares_dnssec_digest_supported(&crypto, 3));
  EXPECT_EQ(4, f.digest_calls);

  // NSEC3: one hash plus one per iteration
  EXPECT_EQ(ARES_SUCCESS,
            ares_dnssec_nsec3_hash(&crypto, data, 4, data, 4, 5, hash));
  EXPECT_EQ(10, f.digest_calls);
  f.digest_len = 32;
  EXPECT_NE(ARES_SUCCESS,
            ares_dnssec_nsec3_hash(&crypto, data, 4, data, 4, 5, hash));
  EXPECT_EQ(11, f.digest_calls);

  // contexts need all the functions
  ares_dnssec_ctx_t   *ctx     = NULL;
  ares_dnssec_crypto_t partial = crypto;
  partial.digest               = NULL;
  EXPECT_EQ(ARES_EFORMERR, ares_dnssec_ctx_create(&partial, &ctx));
  EXPECT_EQ(ARES_EFORMERR, ares_dnssec_ctx_create(NULL, &ctx));
  EXPECT_EQ(nullptr, ctx);
}

