typedef std::vector<unsigned char> Bytes;

static void DerLen(Bytes *out, size_t len)
{
  if (len < 0x80) {
    out->push_back((unsigned char)len);
  } else if (len < 0x100) {
    out->push_back(0x81);
    out->push_back((unsigned char)len);
  } else {
    out->push_back(0x82);
    out->push_back((unsigned char)(len >> 8));
    out->push_back((unsigned char)len);
  }
}

static Bytes DerTag(unsigned char tag, const Bytes &content)
{
  Bytes out;
  out.push_back(tag);
  DerLen(&out, content.size());
  out.insert(out.end(), content.begin(), content.end());
  return out;
}

// A DER INTEGER with an unsigned big-endian value
static Bytes DerUint(const unsigned char *num, size_t len)
{
  while (len > 1 && num[0] == 0) {
    num++;
    len--;
  }
  Bytes content;
  if (len && (num[0] & 0x80)) {
    content.push_back(0);
  }
  content.insert(content.end(), num, num + len);
  return DerTag(0x02, content);
}

// SubjectPublicKeyInfo of a DNSSEC public key.  c-ares has checked the
// format and size of the key.
static Bytes Spki(unsigned char alg, const unsigned char *key, size_t keylen)
{
  static const unsigned char p256[]    = { 0x30, 0x59, 0x30, 0x13, 0x06, 0x07,
                                           0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02,
                                           0x01, 0x06, 0x08, 0x2a, 0x86, 0x48,
                                           0xce, 0x3d, 0x03, 0x01, 0x07, 0x03,
                                           0x42, 0x00, 0x04 };
  static const unsigned char p384[]    = { 0x30, 0x76, 0x30, 0x10, 0x06, 0x07,
                                           0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02,
                                           0x01, 0x06, 0x05, 0x2b, 0x81, 0x04,
                                           0x00, 0x22, 0x03, 0x62, 0x00, 0x04 };
  static const unsigned char ed25519[] = { 0x30, 0x2a, 0x30, 0x05, 0x06, 0x03,
                                           0x2b, 0x65, 0x70, 0x03, 0x21, 0x00 };
  static const unsigned char ed448[]   = { 0x30, 0x43, 0x30, 0x05, 0x06, 0x03,
                                           0x2b, 0x65, 0x71, 0x03, 0x3a, 0x00 };
  // AlgorithmIdentifier for rsaEncryption, with NULL parameters
  static const unsigned char rsa[]  = { 0x30, 0x0d, 0x06, 0x09, 0x2a,
                                        0x86, 0x48, 0x86, 0xf7, 0x0d,
                                        0x01, 0x01, 0x01, 0x05, 0x00 };
  const unsigned char       *prefix = nullptr;
  size_t                     plen   = 0;
  switch (alg) {
    case 13:
      prefix = p256;
      plen   = sizeof(p256);
      break;
    case 14:
      prefix = p384;
      plen   = sizeof(p384);
      break;
    case 15:
      prefix = ed25519;
      plen   = sizeof(ed25519);
      break;
    case 16:
      prefix = ed448;
      plen   = sizeof(ed448);
      break;
    default:
      break;
  }
  if (prefix != nullptr) {
    Bytes out(prefix, prefix + plen);
    out.insert(out.end(), key, key + keylen);
    return out;
  }

  // RSA, RFC 3110 section 2
  size_t explen;
  size_t expoff;
  if (key[0] != 0) {
    explen = key[0];
    expoff = 1;
  } else {
    explen = ((size_t)key[1] << 8) | key[2];
    expoff = 3;
  }
  Bytes seq = DerUint(key + expoff + explen, keylen - expoff - explen);
  Bytes exp = DerUint(key + expoff, explen);
  seq.insert(seq.end(), exp.begin(), exp.end());
  Bytes bits(1, 0);
  Bytes rsakey = DerTag(0x30, seq);
  bits.insert(bits.end(), rsakey.begin(), rsakey.end());
  Bytes spki(rsa, rsa + sizeof(rsa));
  Bytes bitstr = DerTag(0x03, bits);
  spki.insert(spki.end(), bitstr.begin(), bitstr.end());
  return DerTag(0x30, spki);
}

